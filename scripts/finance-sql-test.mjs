import { PGlite } from "@electric-sql/pglite";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
/** Runs migration 0015 on an in-process Postgres (PGlite) and checks every money rule. `npm run test:finance:sql` */
const here = path.dirname(fileURLToPath(import.meta.url));
const db = new PGlite();
const mig = fs.readFileSync(path.join(here, "../supabase/migrations/0015_accounting.sql"), "utf8");

await db.exec(`
create schema auth; create schema storage;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid $$;
create table storage.buckets(id text primary key, name text, public boolean);
create table storage.objects(id serial primary key, bucket_id text, name text);
create type role as enum ('admin','teacher','student');
create table public.profiles(id uuid primary key, role role not null default 'student', full_name text);
create table public.courses(id uuid primary key default gen_random_uuid(), price integer);
create table public.classes(id uuid primary key default gen_random_uuid(), course_id uuid references public.courses(id), teacher_id uuid, title text);
create table public.enrollments(id uuid primary key default gen_random_uuid(), student_id uuid references public.profiles(id), class_id uuid references public.classes(id), unique(student_id,class_id));
create table public.attendance(id uuid primary key default gen_random_uuid(), enrollment_id uuid references public.enrollments(id), session_date date not null);
create table public.books(id uuid primary key default gen_random_uuid(), title jsonb);
create function public.is_admin() returns boolean language sql stable security definer as $$ select coalesce((select role='admin' from public.profiles where id=auth.uid()),false) $$;
`);
await db.exec(mig);
console.log("migration applied OK");

const A="00000000-0000-0000-0000-00000000000a", S="00000000-0000-0000-0000-0000000000b1", T="00000000-0000-0000-0000-0000000000c1";
await db.exec(`insert into auth.users values ('${A}'),('${S}'),('${T}');
insert into profiles values ('${A}','admin','Admin'),('${S}','student','Sara'),('${T}','teacher','Reza');`);
const course=(await db.query(`insert into courses(price) values (4000000) returning id`)).rows[0].id;
const cls=(await db.query(`insert into classes(course_id,teacher_id,title) values ('${course}','${T}','Step 3') returning id`)).rows[0].id;
const enr=(await db.query(`insert into enrollments(student_id,class_id) values ('${S}','${cls}') returning id`)).rows[0].id;
const as = (u)=>db.exec(`select set_config('request.jwt.claim.sub','${u}',false)`);
let pass=0, fail=0;
const ok=(name,cond)=>{ if(cond){pass++;console.log("  ✓",name)}else{fail++;console.log("  ✗ FAIL",name)} };
const throws=async(name,fn,match)=>{ try{await fn(); fail++;console.log("  ✗ FAIL (no error)",name)}catch(e){ const m=String(e.message); if(!match||m.includes(match)){pass++;console.log("  ✓",name,"→",m.slice(0,70))}else{fail++;console.log("  ✗ FAIL wrong error",name,m)} } };
const q=async(sql)=> (await db.query(sql)).rows;

console.log("\n# access control");
await as(S);
await throws("student cannot record payment",()=>db.query(`select fin_record_student_payment('${enr}',1000,'payment','completed','cash',current_date,'','','k0')`),"forbidden");
await as(A);

console.log("\n# student payments");
const pay=(amt,kind='payment',st='completed',key=null)=>db.query(`select fin_record_student_payment('${enr}',${amt},'${kind}','${st}','card',current_date,'ref','',${key?`'${key}'`:'null'}) as id`);
await pay(1500000,'payment','completed','k1');
await pay(1500000,'payment','completed','k1');
ok("idempotent key returns same row (no duplicate)", (await q(`select count(*)::int n from student_payments`))[0].n===1);
await pay(2000000);
ok("fee 4,000,000: received 3,500,000", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===3500000);
await throws("overpayment rejected",()=>pay(600000),"exceeds the remaining balance");
await pay(500000);
ok("fully paid = 4,000,000", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===4000000);
await throws("refund above received rejected",()=>pay(4000001,'refund'),"refund exceeds");
await pay(1000000,'refund');
ok("after 1,000,000 refund net = 3,000,000", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===3000000);
const pend=(await pay(500000,'payment','pending')).rows[0].id;
ok("pending payment is NOT counted as received", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===3000000);
await db.query(`select fin_confirm_student_payment('${pend}', current_date)`);
ok("confirmed pending payment counts", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===3500000);
await throws("direct UPDATE of amount blocked",()=>db.query(`update student_payments set amount=1 where id='${pend}'`),"immutable");
await throws("DELETE blocked",()=>db.query(`delete from student_payments`),"cannot be deleted");
await throws("void needs reason",()=>db.query(`select fin_void_student_payment('${pend}','')`),"reason");
await db.query(`select fin_void_student_payment('${pend}','entered twice')`);
ok("voided payment excluded", Number((await q(`select fin_enrollment_received('${enr}') r`))[0].r)===3000000);
await throws("double void rejected",()=>db.query(`select fin_void_student_payment('${pend}','x')`),"already voided");
await throws("fee below received rejected",()=>db.query(`select fin_set_student_fee('${enr}',1000000)`),"lower than");
await db.query(`select fin_set_student_fee('${enr}',5000000)`);
ok("fee override applies", Number((await q(`select fin_enrollment_fee('${enr}') f`))[0].f)===5000000);

console.log("\n# salaries");
const stm=(rep=false,g=1200000)=>db.query(`select fin_save_salary_statement('${T}','1405-07','2026-09-23','2026-10-22','per_class',200000,6,540,0,${g},${rep}) id`);
const st1=(await stm()).rows[0].id;
await throws("duplicate statement rejected",()=>stm(false),"already exists");
await stm(true,1400000);
ok("recalculation replaces (still one row)", (await q(`select count(*)::int n, max(gross_amount)::int g from salary_statements`))[0].n===1);
const sp=(amt,key)=>db.query(`select fin_record_salary_payment('${st1}',${amt},'bank_transfer',current_date,'','',${key?`'${key}'`:'null'}) id`);
await sp(600000,'s1'); await sp(600000,'s1');
ok("salary payment idempotent", (await q(`select count(*)::int n from salary_payments`))[0].n===1);
await throws("salary overpayment rejected",()=>sp(900000),"exceeds the remaining");
await sp(800000);
ok("fully paid 1,400,000", Number((await q(`select sum(amount) s from salary_payments where voided_at is null`))[0].s)===1400000);
await throws("statement with payments cannot be recalculated",()=>stm(true,1000000),"already has payments");
await throws("statement direct UPDATE blocked",()=>db.query(`update salary_statements set gross_amount=1`),"only be changed");
const spid=(await q(`select id from salary_payments limit 1`))[0].id;
await db.query(`select fin_void_salary_payment('${spid}','wrong account')`);
ok("void frees balance", Number((await q(`select sum(amount) s from salary_payments where voided_at is null`))[0].s)===800000);

console.log("\n# books / inventory");
const book=(await q(`insert into books(title) values ('{"fa":"فور کرنرز","en":"Four Corners"}') returning id`))[0].id;
const inv=(await q(`select fin_inventory_add('${book}',300000) id`))[0].id;
await throws("same book twice rejected",()=>db.query(`select fin_inventory_add('${book}',1)`),"already in");
const buy=(qty,cost,key)=>db.query(`select fin_record_book_purchase('${inv}',${qty},${cost},current_date,'cash','sup','',${key?`'${key}'`:'null'})`);
await buy(10,200000,'p1'); await buy(10,200000,'p1');
ok("purchase idempotent: stock 10", (await q(`select stock_qty from book_inventory`))[0].stock_qty===10);
await buy(5,230000);
let i=(await q(`select * from book_inventory`))[0];
ok("stock 15, value 3,150,000", i.stock_qty===15 && Number(i.stock_value)===3150000);
const sell=(qty,price,key)=>db.query(`select fin_record_book_sale('${inv}',${qty},${price},current_date,'cash',null,'walk-in','',${key?`'${key}'`:'null'}) id`);
const s1=(await sell(4,300000,'x1')).rows[0].id;
let sale=(await q(`select * from book_sales`))[0];
ok("sale: revenue 1,200,000, cogs 840,000 (avg 210,000)", Number(sale.revenue)===1200000 && Number(sale.cogs)===840000);
i=(await q(`select * from book_inventory`))[0];
ok("stock updated to 11, value 2,310,000", i.stock_qty===11 && Number(i.stock_value)===2310000);
await throws("selling more than stock rejected",()=>sell(12,300000),"insufficient stock");
await sell(11,300000);
i=(await q(`select * from book_inventory`))[0];
ok("sell-out leaves stock 0 and value exactly 0 (no rounding drift)", i.stock_qty===0 && Number(i.stock_value)===0);
await db.query(`select fin_void_book_sale('${s1}','customer returned')`);
i=(await q(`select * from book_inventory`))[0];
ok("void sale restores 4 copies at 840,000", i.stock_qty===4 && Number(i.stock_value)===840000);
const p=(await q(`select id from book_purchases order by created_at limit 1`))[0].id;
await throws("cannot void purchase whose copies were sold",()=>db.query(`select fin_void_book_purchase('${p}','x')`),"already been sold");
await throws("direct stock UPDATE blocked",()=>db.query(`update book_inventory set stock_qty=999`),"purchases and sales");
await db.query(`update book_inventory set selling_price=350000`);
ok("selling price editable directly", Number((await q(`select selling_price from book_inventory`))[0].selling_price)===350000);

console.log("\n# expenses / audit");
await throws("manual teacher_salaries expense rejected (double-count guard)",()=>db.query(`insert into expenses(category,amount) values ('teacher_salaries',1)`),"check");
await throws("manual book_purchases expense rejected",()=>db.query(`insert into expenses(category,amount) values ('book_purchases',1)`),"check");
await db.query(`insert into expenses(category,amount,description) values ('rent',15000000,'Mehr rent')`);
await throws("expense DELETE blocked",()=>db.query(`delete from expenses`),"cannot be deleted");
await db.query(`update expenses set amount=16000000`);
ok("expense edit audited (insert+update rows)", (await q(`select count(*)::int n from fin_audit_log where table_name='expenses'`))[0].n===2);
ok("audit log holds before/after for payments", (await q(`select count(*)::int n from fin_audit_log where table_name='student_payments' and action='UPDATE' and old_row is not null`))[0].n>=1);

console.log("\n# held-sessions view + RLS");
await db.exec(`insert into attendance(enrollment_id, session_date) values ('${enr}','2026-10-03'),('${enr}','2026-10-03'),('${enr}','2026-10-07')`);
ok("fin_class_sessions = distinct days per class (2, not 3)", (await q(`select count(*)::int n from fin_class_sessions`))[0].n===2);
await db.exec(`create role app_user; grant usage on schema public, auth to app_user; grant all on all tables in schema public to app_user; grant all on all functions in schema public to app_user; grant select on auth.users to app_user;`);
await db.exec(`set role app_user`);
await as(S);
ok("student sees NO payments (RLS)", (await q(`select count(*)::int n from student_payments`))[0].n===0);
ok("student sees NO expenses (RLS)", (await q(`select count(*)::int n from expenses`))[0].n===0);
ok("student sees NO audit log (RLS)", (await q(`select count(*)::int n from fin_audit_log`))[0].n===0);
await throws("student cannot insert an expense",()=>db.query(`insert into expenses(category,amount) values ('rent',1)`),"row-level security");
await as(A);
ok("admin sees payments", (await q(`select count(*)::int n from student_payments`))[0].n>0);
await throws("admin cannot INSERT a payment directly (must use the function)",()=>db.query(`insert into student_payments(amount) values (1)`),"row-level security");
await db.query(`update salary_statements set gross_amount=1`);
ok("admin direct UPDATE of a salary statement changes nothing (RLS)", Number((await q(`select gross_amount g from salary_statements`))[0].g)===1400000);
await db.exec(`insert into expenses(category,amount,client_key) values ('internet',900000,'ek1')`);
await throws("duplicate expense key rejected",()=>db.query(`insert into expenses(category,amount,client_key) values ('internet',900000,'ek1')`),"client_key");
await db.exec(`reset role`);

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail?1:0);
