export type EK = keyof typeof E;
export type ET = (k: EK) => string;
export const makeET = (locale: Locale): ET => {
  const i = locale === "fa" ? 0 : 1;
  return (k) => E[k][i];
};

const ERR: Array<[RegExp, EK]> = [
  [/registration is closed/i, "e_closed"],
  [/event is full|this event is full/i, "e_full"],
  [/not open for registration/i, "e_notOpen"],
  [/invalid name/i, "e_name"],
  [/invalid phone/i, "e_phone"],
  [/invalid email/i, "e_email"],
  [/too many participants for this event/i, "e_tooMany"],
  [/participants must be between/i, "e_participants"],
  [/already registered/i, "alreadyHere"],
  [/already started/i, "e_notStarted"],
  [/registration not found/i, "notFound"],
  [/forbidden/i, "forbidden"],
  [/does not exist|schema cache/i, "a_needsMigration"],
];

export function friendlyEventError(message: string, locale: Locale): string {
  const t = makeET(locale);
  const hit = ERR.find(([re]) => re.test(message));
  if (hit) return t(hit[1]);
  // admin-facing RPC messages are already readable English; keep them for staff
  return /seats|payment|refund|void|reason|attendance|checked|free|amount|active registration|pending/i.test(message) ? message : t("e_generic");
}
